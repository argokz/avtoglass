<?php

namespace Tests\Unit;

use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

/**
 * Витрина считает вслух: «137 моделей», «1 модель», «22 модели». Пока слово
 * стояло в шаблоне неизменяемым, девять марок в каталоге были подписаны
 * «1 моделей» — мелочь, по которой покупатель решает, что сайт недоделан.
 */
class СклонениеTest extends TestCase
{
    #[DataProvider('числа')]
    public function test_форма_слова_по_числу(int $число, string $ожидается): void
    {
        $this->assertSame($ожидается, склонение($число, 'модель', 'модели', 'моделей'));
    }

    /** @return array<string, array{int, string}> */
    public static function числа(): array
    {
        return [
            'ноль' => [0, 'моделей'],
            'одна' => [1, 'модель'],
            'две' => [2, 'модели'],
            'четыре' => [4, 'модели'],
            'пять' => [5, 'моделей'],
            // 11–14 — исключение: «одиннадцать моделей», а не «моделей/модель»
            'одиннадцать' => [11, 'моделей'],
            'двенадцать' => [12, 'моделей'],
            'четырнадцать' => [14, 'моделей'],
            'двадцать один' => [21, 'модель'],
            'двадцать два' => [22, 'модели'],
            'двадцать пять' => [25, 'моделей'],
            'сто один' => [101, 'модель'],
            'сто одиннадцать' => [111, 'моделей'],
            'тысяча триста восемьдесят один' => [1381, 'модель'],
            'пять тысяч восемьсот шестьдесят семь' => [5867, 'моделей'],
        ];
    }

    /** Отрицательных счётчиков не бывает, но падать на них тоже незачем. */
    public function test_отрицательное_число_не_ломает(): void
    {
        $this->assertSame('модель', склонение(-1, 'модель', 'модели', 'моделей'));
    }

    public function test_слова_подставляются_те_что_передали(): void
    {
        $this->assertSame('год', склонение(1, 'год', 'года', 'лет'));
        $this->assertSame('года', склонение(3, 'год', 'года', 'лет'));
        $this->assertSame('лет', склонение(14, 'год', 'года', 'лет'));
    }
}
